#!/usr/bin/env node
/**
 * Vendors entity icons from the blob-list registry into
 * public/images/entities/ and regenerates
 * src/constants/entityIcons.generated.ts.
 *
 * By default this pulls the latest GitHub release of tirante-dev/blob-list,
 * downloads every entity's resolved icon (Chainlist icons via an IPFS
 * gateway, local registry SVGs from the repo at the release tag), and keys
 * the generated map by lowercased entity name, which is exactly what the
 * indexer sends as user_attribution.
 *
 * Overrides, mainly for testing against a local blob-list checkout:
 *   --icons-json <path|url>     icons.json artifact
 *   --entities-json <path|url>  entities.json artifact
 *   --icon-root <path|url>      base for local-mode SVG paths
 *   --ipfs-gateway <url>        primary IPFS gateway
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'tirante-dev/blob-list';
const FALLBACK_IPFS_GATEWAYS = ['https://ipfs.io/ipfs/', 'https://dweb.link/ipfs/'];
const FETCH_TIMEOUT_MS = 30_000;

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = path.join(rootDir, 'public/images/entities');
const generatedFile = path.join(rootDir, 'src/constants/entityIcons.generated.ts');

const args = parseArgs(process.argv.slice(2));

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});

async function main() {
  let iconsSource = args['icons-json'];
  let entitiesSource = args['entities-json'];
  let iconRoot = args['icon-root'];
  let version;

  if (!iconsSource || !entitiesSource) {
    const release = await fetchJson(
      `https://api.github.com/repos/${REPO}/releases/latest`
    );
    version = release.tag_name;
    const download = `https://github.com/${REPO}/releases/download/${version}`;
    iconsSource ??= `${download}/icons.json`;
    entitiesSource ??= `${download}/entities.json`;
    iconRoot ??= `https://raw.githubusercontent.com/${REPO}/${version}`;
  }
  if (!iconRoot) {
    throw new Error('--icon-root is required when overriding the artifact sources');
  }

  const [icons, entities] = await Promise.all([
    loadJson(iconsSource),
    loadJson(entitiesSource),
  ]);
  version ??= `generated_at ${icons.generated_at}`;

  const entityById = new Map(entities.entities.map((entity) => [entity.id, entity]));

  await fs.mkdir(imagesDir, { recursive: true });
  const kept = new Set();
  const mapEntries = [];
  let written = 0;

  for (const [id, icon] of Object.entries(icons.icons).sort()) {
    const entity = entityById.get(id);
    const resolved = resolveDownload(id, icon, iconRoot);
    if (!entity || !resolved) {
      continue;
    }

    const fileName = `${id}.${resolved.ext}`;
    const bytes = await download(resolved, id);
    const target = path.join(imagesDir, fileName);
    if (!(await sameBytes(target, bytes))) {
      await fs.writeFile(target, bytes);
      written += 1;
    }
    kept.add(fileName);
    const settlement =
      (entity.chain_refs ?? []).find(
        (ref) => ref.relationship === 'settlement_chain'
      )?.caip2 ?? 'eip155-1';
    mapEntries.push([
      entity.name.toLowerCase(),
      `/images/entities/${fileName}`,
      settlement,
    ]);
  }

  let removed = 0;
  for (const file of await fs.readdir(imagesDir)) {
    if (!kept.has(file)) {
      await fs.rm(path.join(imagesDir, file));
      removed += 1;
    }
  }

  mapEntries.sort(([a], [b]) => a.localeCompare(b));
  const lines = mapEntries.map(
    ([key, file, settlement]) =>
      `  '${key}': { src: '${file}', settlement: '${settlement}' },`
  );
  await fs.writeFile(
    generatedFile,
    `// Generated by scripts/sync-entity-icons.mjs; do not edit by hand.\n` +
      `// Refresh with: npm run sync-icons\n` +
      `// Source: ${REPO} ${version}\n\n` +
      `export interface EntityIcon {\n` +
      `  /** Bundled icon path under public/. */\n` +
      `  src: string;\n` +
      `  /** CAIP-2 ref of the entity's settlement chain, e.g. eip155-1. */\n` +
      `  settlement: string;\n` +
      `}\n\n` +
      `/** Lowercased blob-list entity name to bundled icon. */\n` +
      `export const ENTITY_ICONS: Record<string, EntityIcon> = {\n${lines.join('\n')}\n};\n`
  );

  console.log(
    `Synced ${mapEntries.length} entity icons from ${REPO} (${version}): ` +
      `${written} written, ${removed} removed.`
  );
}

/** Decide what to download for one resolved registry icon, or null to skip. */
function resolveDownload(id, icon, iconRoot) {
  if (!icon) {
    return null;
  }
  if (icon.mode === 'local') {
    return { urls: [joinSource(iconRoot, icon.source)], ext: 'svg' };
  }
  const entry = pickEntry(icon.entries ?? []);
  if (!entry) {
    return null;
  }
  const cidPath = entry.url.replace(/^ipfs:\/\//, '');
  const gateways = args['ipfs-gateway']
    ? [args['ipfs-gateway'], ...FALLBACK_IPFS_GATEWAYS]
    : FALLBACK_IPFS_GATEWAYS;
  return {
    urls: gateways.map((gateway) => `${gateway.replace(/\/$/, '')}/${cidPath}`),
    ext: entry.format,
  };
}

/** Prefer SVG entries, then the largest raster. */
function pickEntry(entries) {
  const svg = entries.find((entry) => entry.format === 'svg');
  if (svg) {
    return svg;
  }
  return entries
    .slice()
    .sort((a, b) => (b.width ?? 0) * (b.height ?? 0) - (a.width ?? 0) * (a.height ?? 0))[0];
}

async function download({ urls, ext }, id) {
  let lastError;
  for (const url of urls) {
    try {
      const bytes = await fetchBytes(url);
      assertLooksLike(bytes, ext, `${id} from ${url}`);
      return bytes;
    } catch (error) {
      lastError = error;
    }
  }
  throw lastError;
}

/**
 * Gateways and CDNs return HTML error pages with status 200 often enough
 * that every downloaded file gets a magic-bytes check before it is vendored.
 */
function assertLooksLike(bytes, ext, label) {
  const ok =
    ext === 'svg'
      ? bytes.toString('utf8', 0, 512).trimStart().startsWith('<svg')
      : ext === 'png'
        ? bytes.subarray(0, 4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47]))
        : ext === 'jpg' || ext === 'jpeg'
          ? bytes[0] === 0xff && bytes[1] === 0xd8
          : bytes.length > 0;
  if (!ok) {
    throw new Error(`Downloaded ${label} does not look like a ${ext} file`);
  }
}

function joinSource(root, relativePath) {
  return isUrl(root)
    ? `${root.replace(/\/$/, '')}/${relativePath}`
    : path.join(root, relativePath);
}

async function loadJson(source) {
  if (isUrl(source)) {
    return fetchJson(source);
  }
  return JSON.parse(await fs.readFile(source, 'utf8'));
}

async function fetchJson(url) {
  const bytes = await fetchBytes(url);
  return JSON.parse(bytes.toString('utf8'));
}

async function fetchBytes(source) {
  if (!isUrl(source)) {
    return fs.readFile(source);
  }
  const response = await fetch(source, {
    headers: { 'user-agent': 'blob-flow sync-entity-icons' },
    redirect: 'follow',
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  if (!response.ok) {
    throw new Error(`GET ${source} failed: ${response.status}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

function isUrl(value) {
  return /^https?:\/\//.test(value);
}

async function sameBytes(file, bytes) {
  try {
    return bytes.equals(await fs.readFile(file));
  } catch {
    return false;
  }
}

function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i];
    const value = argv[i + 1];
    if (!key.startsWith('--') || value === undefined) {
      throw new Error(`Unexpected argument: ${key}`);
    }
    parsed[key.slice(2)] = value;
  }
  return parsed;
}
